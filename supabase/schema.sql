create table if not exists public.portfolio_submissions (
  id bigint generated by default as identity primary key,
  reference_id text not null unique,
  submitted_at timestamptz not null default now(),
  full_name text not null,
  email text not null,
  career_field text not null,
  preferred_design text not null check (preferred_design in ('developer', 'creative', 'professional')),
  color_option text not null,
  custom_primary_color text,
  custom_accent_color text,
  contact_method text not null,
  project_notes text,
  cv_builder_waitlist boolean not null default false,
  agreed_to_terms boolean not null default false check (agreed_to_terms)
);

create table if not exists public.cv_builder_waitlist (
  id bigint generated by default as identity primary key,
  email text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.performance_events (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  event_name text not null check (event_name in ('visit', 'return_visit', 'conversion_click', 'footer_reached')),
  event_label text,
  occurred_at timestamptz not null default now()
);

create index if not exists performance_events_occurred_at_idx on public.performance_events (occurred_at);
create index if not exists performance_events_name_occurred_at_idx on public.performance_events (event_name, occurred_at);
create index if not exists performance_events_visitor_id_idx on public.performance_events (visitor_id);

alter table public.portfolio_submissions enable row level security;
alter table public.cv_builder_waitlist enable row level security;
alter table public.performance_events enable row level security;

-- Public visitors may submit forms but may not read or edit stored submissions.
drop policy if exists "Anyone can submit portfolio inquiries" on public.portfolio_submissions;
create policy "Anyone can submit portfolio inquiries"
  on public.portfolio_submissions for insert to anon, authenticated
  with check (true);

drop policy if exists "Anyone can join the CV builder waitlist" on public.cv_builder_waitlist;
create policy "Anyone can join the CV builder waitlist"
  on public.cv_builder_waitlist for insert to anon, authenticated
  with check (true);

drop policy if exists "Anyone can confirm a waitlist email" on public.cv_builder_waitlist;
create policy "Anyone can confirm a waitlist email"
  on public.cv_builder_waitlist for select to anon, authenticated
  using (true);

-- Anonymous visitors can add performance events but cannot read them.
drop policy if exists "Anyone can record performance events" on public.performance_events;
create policy "Anyone can record performance events"
  on public.performance_events for insert to anon, authenticated
  with check (true);

create or replace view public.performance_event_counts as
select
  event_name,
  event_label,
  date_trunc('day', occurred_at) as event_day,
  count(*) as event_count,
  count(distinct visitor_id) as unique_visitors
from public.performance_events
group by event_name, event_label, date_trunc('day', occurred_at);
